// Builds the page's responsive images from the originals in src/assets/source/.
//
//   npm run images
//
// For every source file it writes AVIF and WebP copies at a few widths into
// src/assets/images/, plus a tiny blurred placeholder, and regenerates
// src/assets/images/index.js, which the page imports. Commit the output.
// Add a project screenshot by dropping a PNG/JPEG/WebP (16:10 works best)
// into src/assets/source/ and running the script again.
import { mkdir, readdir, rm, writeFile } from "node:fs/promises";
import { extname, basename } from "node:path";
import { fileURLToPath } from "node:url";
import sharp from "sharp";

const root = fileURLToPath(new URL("..", import.meta.url));
const sourceDir = `${root}src/assets/source/`;
const outDir = `${root}src/assets/images/`;

// Widths per image. Screenshots fill the content column (up to ~1046 CSS px);
// the avatar shows at 96-112 CSS px.
const screenshot = { widths: [480, 800, 1280], aspect: 10 / 16, position: "top" };
const special = {
  avatar: { widths: [112, 224, 336], aspect: 1, position: "centre" },
};

const files = (await readdir(sourceDir)).filter((f) => /\.(png|jpe?g|webp)$/i.test(f)).sort();
await rm(outDir, { recursive: true, force: true });
await mkdir(outDir, { recursive: true });

const imports = [];
const entries = [];

for (const file of files) {
  const name = basename(file, extname(file));
  const { widths, aspect, position } = special[name] ?? screenshot;
  const key = name.replace(/[^a-z0-9]/gi, "_");
  const avif = [];
  const webp = [];

  for (const width of widths) {
    const height = Math.round(width * aspect);
    const resized = () => sharp(`${sourceDir}${file}`).resize({ width, height, fit: "cover", position });
    for (const [format, list, options] of [
      ["avif", avif, { quality: 55, effort: 6 }],
      ["webp", webp, { quality: 76, effort: 6 }],
    ]) {
      const out = `${name}-${width}.${format}`;
      await resized()[format](options).toFile(`${outDir}${out}`);
      const id = `${key}_${format}_${width}`;
      imports.push(`import ${id} from "./${out}";`);
      list.push(`[${width}, ${id}]`);
    }
  }

  const largest = widths[widths.length - 1];
  const placeholder = await sharp(`${sourceDir}${file}`)
    .resize({ width: 16, height: Math.round(16 * aspect), fit: "cover", position })
    .webp({ quality: 40 })
    .toBuffer();

  entries.push(`  ${JSON.stringify(name)}: {
    width: ${largest},
    height: ${Math.round(largest * aspect)},
    avif: [${avif.join(", ")}],
    webp: [${webp.join(", ")}],
    src: ${key}_webp_${largest},
    placeholder: "data:image/webp;base64,${placeholder.toString("base64")}",
  },`);
  console.log(`${file}: ${widths.join(", ")}w`);
}

await writeFile(
  `${outDir}index.js`,
  `// Generated by scripts/images.mjs from src/assets/source/. Do not edit by hand.\n${imports.join("\n")}\n\nexport const images = {\n${entries.join("\n")}\n};\n`,
);
